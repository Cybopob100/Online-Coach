export type Lang = 'en' | 'pl' | 'uk' | 'ru';

export const LANGS: { code: Lang; name: string; strings: Strings; locale: string }[] = [
  { code: 'en', name: 'English', strings: en, locale: 'en-GB' },
  { code: 'pl', name: 'Polski', strings: pl, locale: 'pl-PL' },
  { code: 'uk', name: 'Українська', strings: uk, locale: 'uk-UA' },
  { code: 'ru', name: 'Русский', strings: ru, locale: 'ru-RU' },
];

function detectLang(): Lang {
  const device = (Intl.DateTimeFormat().resolvedOptions().locale || 'en').toLowerCase();
  return LANGS.find((l) => device.startsWith(l.code))?.code ?? 'en';
}

let current: Lang = detectLang();

/** Тексты на текущем языке. Всегда читают актуальный язык. */
export const t: Strings = new Proxy({} as Strings, {
  get: (_target, key) => (LANGS.find((l) => l.code === current)!.strings as Record<string | symbol, unknown>)[key],
});

export const getLang = () => current;
export const setCurrentLang = (lang: Lang) => {
  current = lang;
};
export const dateLocale = () => LANGS.find((l) => l.code === current)!.locale;

export const errorText = (code: string) => t.errors[code] ?? t.errors.server_error;
